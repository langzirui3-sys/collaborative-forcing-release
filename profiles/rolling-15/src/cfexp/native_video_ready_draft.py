"""Pure native Draft with the same accepted-video renderer as mixed campaigns.

The root is generated by Draft. Target remains resident for its independent VAE
worker only; this trajectory never calls Target denoising or uses a Target root.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from types import SimpleNamespace

from .correction_state import LatentHistory
from .insight2_campaign import ChunkGenerationRequest, PromptCase

SELF_FORCING = 'self_forcing_1.3b'
MODELS = ('longlive_1.3b', 'rolling_forcing_1.3b', SELF_FORCING)


def validate_cache(diagnostics, *, model, index):
    if model in ('longlive_1.3b', SELF_FORCING):
        state = diagnostics['kv_reuse']
        if (type(state.get('replayed_chunks')) is not int or state['replayed_chunks'] != 0
                or type(state.get('reused_chunks')) is not int or state['reused_chunks'] != index):
            raise ValueError('pure Draft did not retain its native accepted cache')
        if model == SELF_FORCING and (state.get('schema') != 'draft_kv_reuse_v2'
                                      or state.get('history_kv_widths') != [3] * index):
            raise ValueError('pure Self-Forcing Draft did not cache all three native latent frames')
    elif model == 'rolling_forcing_1.3b':
        state = diagnostics['rolling_state']
        if (type(state.get('chunk_index')) is not int or state['chunk_index'] != index
                or state.get('state_policy') != 'single_active_branch_clean_history_restart_v1'
                or state.get('reused_rolling_state') is not (index > 0)
                or type(state.get('replayed_history_blocks')) is not int
                or state['replayed_history_blocks'] != 0
                or state.get('discarded_future_state') is not False):
            raise ValueError('pure Rolling Draft did not retain its native rolling state')
    else:
        raise ValueError('unsupported native pure Draft model')
    return dict(state)


def generate(*, draft, noise_provider, prompt_id, prompt, chunk_count, model, renderer,
             run_dir):
    if model not in MODELS or type(chunk_count) is not int or chunk_count not in (30, 60, 120):
        raise ValueError('unsupported native pure Draft horizon/model')
    if draft.model_id != model or draft.role != 'draft':
        raise ValueError('pure Draft client identity differs from the native model')
    from .paper_population import generation_seed
    seed = generation_seed()
    key = hashlib.sha256(f'native-pure-draft:{model}:{prompt_id}:{seed}:{chunk_count}'.encode()).hexdigest()
    history = LatentHistory(key, prompt_id, seed)
    case = PromptCase(prompt_id, prompt, 'evaluation')
    states = []
    for index in range(chunk_count):
        noise = noise_provider.materialize(prompt_id=prompt_id,
            trajectory_seed=seed, chunk_index=index)
        request = ChunkGenerationRequest(prompt=case, history=history, noise=noise,
            output_latent_path=f'latents/native-draft/{prompt_id}/{index:03d}.safetensors',
            capture_hidden=False)
        renderer.before_generate('draft')
        item = draft.generate(request)
        item.segment.verify_context(history, item.context)
        item.segment.verify_file(run_dir)
        if item.segment.producer_role != 'draft':
            raise ValueError('pure Draft received another producer role')
        state = validate_cache(item.diagnostics, model=model, index=index)
        history = history.append(item.segment)
        renderer.append(history)
        states.append(dict(chunk_index=index, cache=state,
            latent_sha256=item.segment.latent_sha256,
            initial_noise_descriptor_sha256=item.segment.initial_noise_descriptor_sha256))
    return SimpleNamespace(history=history, result=dict(
        schema='native_pure_draft_trajectory_v1', draft_model_id=model,
        initialization='pure_native_draft_no_target_root', seed=seed,
        prompt_id=prompt_id, chunk_count=chunk_count, draft_model_calls=chunk_count,
        target_model_calls=0, history_reconstruction_calls=0,
        history_head_sha256=history.head_sha256,
        history_manifest_sha256=history.manifest_sha256, native_cache_states=states))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('draft-artifact-spec', 'target-artifact-spec', 'vbench-checkout',
                 'vbench-python', 'vbench-asset-manifest', 'vbench-asset-spec'):
        parser.add_argument('--'+name, type=Path, required=True)
    parser.add_argument('--duration-seconds', type=int, choices=(15, 30, 60), required=True)
    parser.add_argument('--smoke-prompt-id')
    parser.add_argument('--overlap-native-vae', action='store_true', required=True)
    parser.add_argument('--native-draft-model-id', choices=MODELS, required=True)
    from .native_video_ready_target import run
    from .runtime_helpers import shutdown_owned_runtime_helpers
    try:
        print(json.dumps(run(**vars(parser.parse_args()), pure_draft=True)))
    finally:
        shutdown_owned_runtime_helpers(label='native-video-ready-draft')


if __name__ == '__main__':
    main()
