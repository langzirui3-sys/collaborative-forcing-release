"""Full-Target rollout core for the frozen six-method main-table benchmark.

This module deliberately reuses the audited correction-runtime contracts.  It
does not load either model itself: the caller supplies the isolated Target
worker, the Draft worker used only for offline VAE decoding, and the shared
deterministic noise provider.  Every one of the 120 chunks is generated by the
Krea 14B Target; no Draft generation or accept/reject gate is permitted.
"""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import math
import time
from typing import Any, Callable, Mapping, Protocol

from .correction_runtime import DecodeResult
from .correction_state import LatentHistory
from .insight2_campaign import (
    ChunkBackendClient,
    ChunkGenerationRequest,
    GeneratedChunk,
    NoiseProvider,
    PromptCase,
)


SCHEMA = "main_table_full_target_rollout_v1"
METHOD_ID = "full_target"
TARGET_MODEL_ID = "krea-realtime-video-14b"
SEED = 20260911
CHUNK_COUNT = 120
LATENT_FRAMES_PER_CHUNK = 3
RGB_FRAME_COUNT = 1437
FPS = 24
HEIGHT = 480
WIDTH = 832
TARGET_RPC_PHASE = "route_materialization"


class FullTargetError(RuntimeError):
    """Raised when the all-Target trajectory or its evidence drifts."""


class DecoderClient(Protocol):
    role: str

    def decode(
        self,
        *,
        history: LatentHistory,
        output_frames_path: str,
        output_video_path: str | None,
        fps: int = 24,
    ) -> DecodeResult: ...


class PersistentTargetClient(ChunkBackendClient, Protocol):
    """Target backend whose prompt/session setup is outside measured generation."""

    session_policy: str
    decode_during_generation: bool

    def start_trajectory(
        self, *, prompt_id: str, prompt: str, seed: int, chunk_count: int
    ) -> Mapping[str, Any]: ...

    def finish_trajectory(self, *, session_id: str) -> Mapping[str, Any]: ...

    def generate_persistent(self, request: ChunkGenerationRequest) -> GeneratedChunk: ...


@dataclass(frozen=True)
class FullTargetGeneration:
    history: LatentHistory
    generated: tuple[GeneratedChunk, ...]
    result: Mapping[str, Any]


@dataclass(frozen=True)
class FullTargetRollout:
    history: LatentHistory
    generated: tuple[GeneratedChunk, ...]
    decode: DecodeResult
    result: Mapping[str, Any]


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise FullTargetError(message)


def _canonical_sha256(*values: Any) -> str:
    payload = json.dumps(
        list(values),
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def _finite_nonnegative(value: Any, label: str) -> float:
    try:
        parsed = float(value)
    except (TypeError, ValueError) as error:
        raise FullTargetError(f"{label} is invalid") from error
    _require(math.isfinite(parsed) and parsed >= 0.0, f"{label} is invalid")
    return parsed


def generate_full_target_trajectory(
    *,
    prompt_id: str,
    prompt: str,
    target: PersistentTargetClient,
    noise_provider: NoiseProvider,
    seed: int = SEED,
    chunk_count: int = CHUNK_COUNT,
    duration_seconds: int | None = None,
    clock: Callable[[], float] = time.perf_counter,
    safety_check: Callable[[str, int], None] | None = None,
    on_commit: Callable[[LatentHistory], None] | None = None,
) -> FullTargetGeneration:
    """Generate one immutable all-Target trajectory without decoding it.

    The main-table generation wall time spans exactly the 120 Target RPCs. Model
    loading, deterministic noise materialization, VAE decode, MP4 encoding, and
    VBench evaluation are outside that interval.  The Target worker copies each
    returned latent to CPU before replying, so each RPC closes the asynchronous
    CUDA work before the wall interval advances. The separate duration profile
    times the entire requested generation loop, including noise/bookkeeping;
    its RPC-only sum is retained as a secondary diagnostic.
    """

    _require(seed == SEED, f"main-table seed must be {SEED}")
    if duration_seconds is None:
        _require(chunk_count == CHUNK_COUNT, f"Full Target requires {CHUNK_COUNT} chunks")
    else:
        from .duration_sweep import duration_profile
        _require(chunk_count == duration_profile(duration_seconds).chunk_count,
                 "Full Target duration/horizon mismatch")
    _require(target.role == "target", "Full Target requires the Target worker")
    _require(target.model_id == TARGET_MODEL_ID, "Full Target loaded the wrong Target model")
    _require(
        target.session_policy == "persistent_native_session",
        "Full Target requires one persistent native Target session",
    )
    _require(
        target.decode_during_generation is False,
        "Full Target generation timing must exclude interleaved VAE decode",
    )
    case = PromptCase(prompt_id=prompt_id, prompt=prompt, split="evaluation")
    trajectory_id = _canonical_sha256(METHOD_ID, prompt_id, seed, chunk_count)
    scope_id = _canonical_sha256(
        "main-table-target-scope-v1", METHOD_ID, prompt_id, seed
    )
    session = target.start_trajectory(
        prompt_id=prompt_id,
        prompt=prompt,
        seed=seed,
        chunk_count=chunk_count,
    )
    _require(
        isinstance(session, Mapping)
        and set(session) == {"session_id", "prompt_encode_seconds"}
        and isinstance(session.get("session_id"), str)
        and bool(session["session_id"]),
        "Target persistent-session startup evidence is invalid",
    )
    session_id = str(session["session_id"])
    prompt_encode_seconds = _finite_nonnegative(
        session["prompt_encode_seconds"], "Target prompt encode time"
    )
    history = LatentHistory(
        trajectory_id=trajectory_id,
        prompt_id=prompt_id,
        trajectory_seed=seed,
    )
    generated: list[GeneratedChunk] = []
    chunk_timings: list[dict[str, Any]] = []

    loop_started = clock() if duration_seconds is not None else None
    for chunk_index in range(chunk_count):
        if safety_check is not None:
            safety_check("before_chunk", chunk_index)
        noise = noise_provider.materialize(
            prompt_id=prompt_id,
            trajectory_seed=seed,
            chunk_index=chunk_index,
        )
        logical_call_id = _canonical_sha256(
            "main-table-target-call-v1",
            METHOD_ID,
            prompt_id,
            seed,
            chunk_index,
            history.head_sha256,
            noise.descriptor.descriptor_sha256,
        )
        output_path = (
            f"latents/{METHOD_ID}/{prompt_id}/chunk-{chunk_index:03d}-target.safetensors"
        )
        request = ChunkGenerationRequest(
            prompt=case,
            history=history,
            noise=noise,
            output_latent_path=output_path,
            capture_hidden=False,
            target_logical_call_id=logical_call_id,
            target_call_scope_id=scope_id,
            target_call_phase=TARGET_RPC_PHASE,
        )
        started = clock()
        item = target.generate_persistent(request)
        if safety_check is not None:
            safety_check("after_chunk", chunk_index)
        elapsed = _finite_nonnegative(clock() - started, "Target chunk wall time")
        _require(item.context.role == "target", "Full Target received a non-Target chunk")
        _require(
            item.context.model_id == TARGET_MODEL_ID,
            "Full Target chunk model identity drifted",
        )
        _require(
            item.target_logical_call_id == logical_call_id,
            "Target worker returned the wrong logical call identity",
        )
        _require(
            item.segment.producer_role == "target",
            "Full Target trajectory contains a Draft-produced segment",
        )
        diagnostics = item.diagnostics
        _require(
            isinstance(diagnostics, Mapping)
            and diagnostics.get("native_session_id") == session_id
            and diagnostics.get("native_session_block_index") == chunk_index
            and diagnostics.get("session_recreated") is False
            and diagnostics.get("history_reconstructed") is False
            and diagnostics.get("vae_decode_performed") is False,
            "Full Target backend did not preserve one decode-free native session",
        )
        generation_cuda_seconds = _finite_nonnegative(
            diagnostics.get("generation_cuda_seconds"),
            "Target chunk CUDA generation time",
        )
        item.segment.verify_context(history, item.context)
        history = history.append(item.segment)
        if on_commit is not None:
            on_commit(history)
        generated.append(item)
        from .native_rank_indices import enabled as index_reuse_enabled
        index_evidence = {}
        if index_reuse_enabled("CFEXP_KV_WITNESS_INDEX_REUSE"):
            _require("kv_witness_index_reuse" in diagnostics,
                "Target witness index reuse lacks physical evidence")
            index_evidence = {
                "kv_witness_index_reuse": diagnostics["kv_witness_index_reuse"],
                "kv_witness_sha256": diagnostics["kv_witness_sha256"],
                "kv_witness": diagnostics["kv_witness"],
            }
        chunk_timings.append(
            {
                **index_evidence,
                "chunk_index": chunk_index,
                "generation_wall_seconds": elapsed,
                "generation_cuda_seconds": generation_cuda_seconds,
                "target_attempt_id": item.target_attempt_id,
                "target_logical_call_id": logical_call_id,
                "latent_sha256": item.segment.latent_sha256,
                "history_head_sha256": history.head_sha256,
            }
        )

    finished = target.finish_trajectory(session_id=session_id)
    _require(
        isinstance(finished, Mapping)
        and set(finished) == {"session_id", "generated_block_count"}
        and finished.get("session_id") == session_id
        and finished.get("generated_block_count") == chunk_count,
        "Target persistent-session completion evidence is invalid",
    )

    _require(history.next_chunk_index == chunk_count, "Full Target horizon is incomplete")
    _require(
        len(generated) == chunk_count
        and all(item.segment.producer_role == "target" for item in generated),
        "Full Target did not produce exactly the requested Target chunks",
    )
    generation_wall_seconds = math.fsum(
        float(item["generation_wall_seconds"]) for item in chunk_timings
    )
    generation_loop_wall_seconds = (
        _finite_nonnegative(clock() - loop_started, "Target generation loop time")
        if loop_started is not None else None
    )
    target_rpc_wall_seconds = generation_wall_seconds
    if generation_loop_wall_seconds is not None:
        generation_wall_seconds = generation_loop_wall_seconds
    generation_cuda_seconds = math.fsum(
        float(item["generation_cuda_seconds"]) for item in chunk_timings
    )
    result = {
        "schema": SCHEMA,
        "method_id": METHOD_ID,
        "prompt_id": prompt_id,
        "seed": seed,
        "target_model_id": TARGET_MODEL_ID,
        "trajectory_id": trajectory_id,
        "history_manifest_sha256": history.manifest_sha256,
        "history_head_sha256": history.head_sha256,
        "chunk_count": chunk_count,
        "latent_frame_count": chunk_count * LATENT_FRAMES_PER_CHUNK,
        "rgb_frame_count": chunk_count * 12 - 3,
        "fps": FPS,
        "height": HEIGHT,
        "width": WIDTH,
        "draft_model_calls": 0,
        "target_model_calls": chunk_count,
        "target_session_policy": "persistent_native_session",
        "target_session_count": 1,
        "target_native_session_id": session_id,
        "history_reconstruction_calls": 0,
        "interleaved_decode": on_commit is not None,
        "accept_reject_gate": False,
        "timing": {
            "primary_latency_field": "generation_wall_seconds",
            "generation_wall_seconds": generation_wall_seconds,
            "generation_cuda_seconds": generation_cuda_seconds,
            "prompt_encode_seconds": prompt_encode_seconds,
            "model_load_included": False,
            "noise_materialization_included": duration_seconds is not None,
            "decode_included": False,
            "video_encode_included": False,
            "vbench_included": False,
            "per_chunk": chunk_timings,
        },
    }
    if duration_seconds is not None:
        result["timing"].update(
            target_rpc_wall_seconds=target_rpc_wall_seconds,
            generation_loop_overheads_included=True,
        )
    return FullTargetGeneration(
        history=history,
        generated=tuple(generated),
        result=result,
    )


def decode_full_target_trajectory(
    *,
    generation: FullTargetGeneration,
    decoder: DecoderClient,
    clock: Callable[[], float] = time.perf_counter,
) -> FullTargetRollout:
    """Decode a completed Target trajectory after the generation timer closed."""

    _require(decoder.role == "draft", "offline VAE decode must use the Draft worker")
    prompt_id = str(generation.result["prompt_id"])
    decode_started = clock()
    decode = decoder.decode(
        history=generation.history,
        output_frames_path=f"decoded/{METHOD_ID}/{prompt_id}.safetensors",
        output_video_path=f"videos/{METHOD_ID}/{prompt_id}.mp4",
        fps=FPS,
    )
    decode_wall_seconds = _finite_nonnegative(
        clock() - decode_started, "Full Target decode wall time"
    )
    _require(decode.video is not None, "Full Target decoder did not emit an MP4")
    video = dict(decode.video)
    _require(video.get("fps") == FPS, "Full Target video FPS drifted")
    _require(video.get("frames") == generation.result["rgb_frame_count"], "Full Target frame count drifted")
    timing = dict(generation.result["timing"])
    timing["vae_decode_and_video_encode_wall_seconds"] = decode_wall_seconds
    result = {**dict(generation.result), "timing": timing, "video": video}
    return FullTargetRollout(
        history=generation.history,
        generated=generation.generated,
        decode=decode,
        result=result,
    )


def run_full_target_rollout(
    *,
    prompt_id: str,
    prompt: str,
    target: PersistentTargetClient,
    decoder: DecoderClient,
    noise_provider: NoiseProvider,
    seed: int = SEED,
    chunk_count: int = CHUNK_COUNT,
    duration_seconds: int | None = None,
    clock: Callable[[], float] = time.perf_counter,
    safety_check: Callable[[str, int], None] | None = None,
) -> FullTargetRollout:
    generation = generate_full_target_trajectory(
        prompt_id=prompt_id,
        prompt=prompt,
        target=target,
        noise_provider=noise_provider,
        seed=seed,
        chunk_count=chunk_count,
        duration_seconds=duration_seconds,
        clock=clock,
        safety_check=safety_check,
    )
    return decode_full_target_trajectory(
        generation=generation,
        decoder=decoder,
        clock=clock,
    )


